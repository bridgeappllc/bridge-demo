"""DB tests for reminders (20261014120000_reminders.sql + 20261014180000_remind_inapp.sql: in-app for everyone, email only if emailable)."""
import json, os, uuid, psycopg
DSN = os.environ.get("DSN", "postgresql://postgres@127.0.0.1:54322/postgres")
conn = psycopg.connect(DSN, autocommit=True)
passed = failed = 0
def new_user(name):
    uid = str(uuid.uuid4())
    conn.execute("insert into auth.users (id, instance_id, aud, role, is_anonymous, created_at, updated_at) values (%s, '00000000-0000-0000-0000-000000000000', 'authenticated', 'authenticated', true, now(), now())", (uid,))
    if name: run(uid, "insert into profiles (id, display_name) values (%s, %s)", (uid, name))
    return uid
def run(uid, sql, params=()):
    with conn.transaction():
        with conn.cursor() as cur:
            if uid == "service":
                cur.execute("set local role service_role"); cur.execute("select set_config('request.jwt.claims', %s, true)", (json.dumps({"role": "service_role"}),))
            elif uid is None:
                cur.execute("set local role anon"); cur.execute("select set_config('request.jwt.claims', %s, true)", (json.dumps({"role": "anon"}),))
            else:
                cur.execute("set local role authenticated"); cur.execute("select set_config('request.jwt.claims', %s, true)", (json.dumps({"sub": uid, "role": "authenticated"}),))
            cur.execute(sql, params)
            return cur.fetchall() if cur.description else cur.rowcount
def check(name, cond):
    global passed, failed
    if cond: passed += 1; print("  PASS", name)
    else: failed += 1; print("  FAIL", name)
def denied(name, uid, sql, params=()):
    try:
        r = run(uid, sql, params); ok = (r == 0 or r == [] or r == [(None,)])
        check(f"{name} (filtered: {r})" if ok else f"{name} -> unexpectedly allowed: {r}", ok)
    except psycopg.Error as e: check(f"{name} (error: {str(e).splitlines()[0][:70]})", True)
def raises(name, uid, sql, params=(), like=""):
    try: r = run(uid, sql, params); check(f"{name} -> unexpectedly ok: {r}", False)
    except psycopg.Error as e: check(f"{name} (error: {str(e).splitlines()[0][:70]})", like.lower() in str(e).lower())
adm = lambda sql, p=(): conn.execute(sql, p).fetchall()
tag = str(uuid.uuid4().int)[:6]  # digits only: random hex can trip the name filter
def confirm(u, email): conn.execute("update auth.users set email=%s, email_confirmed_at=now(), is_anonymous=false where id=%s", (email, u))
A, B, C, G, E, X = (new_user(n) for n in (f"Ann{tag}", f"Ben{tag}", f"Cat{tag}", f"Guy{tag}", f"Eve{tag}", f"Xan{tag}"))
for u, n in ((A, "a"), (B, "b"), (C, "c"), (E, "e"), (X, "x")): confirm(u, f"{n}-{tag}@test.local")
prep = lambda s, k, p, t, dry=False: run("service", "select reminder_id, email, sender_name, clip_title from remind_prepare(%s,%s,%s,%s,%s)", (s, k, p, t, dry))
b = run(A, "select id, invite_token from create_bridge(%s,'Remind me','https://example.org/rem')", (f"Ann{tag}",))[0]; bid = str(b[0])
run(B, "select join_bridge(%s,%s)", (b[1], f"Ben{tag}"))
print("access")
raises("authenticated users can't call remind_prepare (emails stay server-side)", A, "select * from remind_prepare(%s,'bridge',%s,%s,false)", (A, bid, B), "permission denied")
raises("anon can't call remind_prepare", None, "select * from remind_prepare(%s,'bridge',%s,%s,false)", (A, bid, B), "permission denied")
raises("authenticated can't call remind_finish", A, "select remind_finish(1,true)", (), "permission denied")
raises("anon can't call remindable", None, "select remindable('bridge',%s)", (bid,), "permission denied")
check("remindable returns ids only", [str(r[0]) for r in run(A, "select remindable('bridge',%s)", (bid,))] == [B])
print("2-person rules")
try: prep(E, "bridge", bid, B); check("non-member can't remind -> unexpectedly ok", False)
except psycopg.Error as e: check("non-member can't remind", "Pod not found" in str(e))
for name, args, like in [("can't remind yourself", (A, "bridge", bid, A), "yourself"), ("target must be in the pod", (A, "bridge", bid, C), "not in this pod")]:
    try: prep(*args); check(name + " -> unexpectedly ok", False)
    except psycopg.Error as e: check(name, like in str(e))
d = prep(A, "bridge", bid, B, True)[0]; check("dry run returns email + clip without reserving", d[0] is None and d[1] == f"b-{tag}@test.local" and d[3] == "Remind me" and adm("select count(*) from pod_reminders") == [(0,)] or adm("select count(*) from pod_reminders where pod_id=%s", (bid,)) == [(0,)])
r = prep(A, "bridge", bid, B)[0]; check("prepare reserves a pending reminder", r[0] is not None and adm("select status from pod_reminders where id=%s", (r[0],)) == [("pending",)])
check("no notification until sent", adm("select count(*) from notifications where user_id=%s and kind='reminder'", (B,)) == [(0,)])
run("service", "select remind_finish(%s,true)", (r[0],))
check("finish(ok) marks sent + notifies the target in-app", adm("select status from pod_reminders where id=%s", (r[0],)) == [("sent",)] and adm("select actor_name, title from notifications where user_id=%s and kind='reminder'", (B,)) == [(f"Ann{tag}", "Remind me")])
try: prep(A, "bridge", bid, B); check("24h limit -> unexpectedly ok", False)
except psycopg.Error as e: check("1 reminder per target per pod per 24h", "24 hours" in str(e))
check("sender reads own reminders (for the Reminded state)", len(run(A, "select id from pod_reminders where pod_id=%s", (bid,))) == 1)
check("others can't read them", run(B, "select count(*) from pod_reminders") == [(0,)])
denied("users can't insert reminders directly", A, "insert into pod_reminders (sender,target,pod_kind,pod_id) values (auth.uid(),%s,'bridge',%s)", (B, bid))
b2 = run(A, "select id, invite_token from create_bridge(%s,'Second','https://example.org/rem2')", (f"Ann{tag}",))[0]; b2id = str(b2[0]); run(B, "select join_bridge(%s,%s)", (b2[1], f"Ben{tag}"))
r2 = prep(A, "bridge", b2id, B)[0]; run("service", "select remind_finish(%s,false)", (r2[0],))
check("finish(failed) frees the slot so you can retry", adm("select count(*) from pod_reminders where id=%s", (r2[0],)) == [(0,)] and prep(A, "bridge", b2id, B, True)[0][1] is not None)
run(B, "insert into answers (bridge_id,user_id,a3,rating) values (%s,auth.uid(),'done',6)", (b2id,))
try: prep(A, "bridge", b2id, B, True); check("answered -> unexpectedly ok", False)
except psycopg.Error as e: check("can't remind someone who already answered", "already answered" in str(e))
print("guests, opt-out, blocks")
b3 = run(A, "select id, invite_token from create_bridge(%s,'Third','https://example.org/rem3')", (f"Ann{tag}",))[0]; b3id = str(b3[0]); run(G, "select join_bridge(%s,%s)", (b3[1], f"Guy{tag}"))
check("guests are offered in remindable (in-app)", [str(x[0]) for x in run(A, "select remindable('bridge',%s)", (b3id,))] == [G])
check("guest reminder is in-app only (no email returned)", prep(A, "bridge", b3id, G, True)[0][1] is None)
rg0 = prep(A, "bridge", b3id, G)[0]; run("service", "select remind_finish(%s,true)", (rg0[0],))
check("guest gets the in-app notification", adm("select count(*) from notifications where user_id=%s and kind='reminder'", (G,)) == [(1,)])
conn.execute("delete from pod_reminders where id=%s", (rg0[0],))
conn.execute("update auth.users set email=%s, email_confirmed_at=null, is_anonymous=false where id=%s", (f"g-{tag}@test.local", G))
check("unconfirmed email -> in-app only", prep(A, "bridge", b3id, G, True)[0][1] is None)
b4 = run(A, "select id, invite_token from create_bridge(%s,'Fourth','https://example.org/rem4')", (f"Ann{tag}",))[0]; b4id = str(b4[0]); run(C, "select join_bridge(%s,%s)", (b4[1], f"Cat{tag}"))
check("C is remindable", [str(x[0]) for x in run(A, "select remindable('bridge',%s)", (b4id,))] == [C])
check("C turns off 'Email me reminders'", run(C, "update profiles set email_reminders=false where id=auth.uid()") == 1)
check("opt-out honored: in-app only, no email", prep(A, "bridge", b4id, C, True)[0][1] is None)
print("pending direct send")
D = str(run(A, "select send_direct_bridge(%s,'Direct ep','https://example.org/dir')", (X,))[0][0])
check("pending direct-send recipient is remindable", [str(x[0]) for x in run(A, "select remindable('bridge',%s)", (D,))] == [X])
check("…with email when they can get it", prep(A, "bridge", D, X, True)[0][1] == f"x-{tag}@test.local")
rd = prep(A, "bridge", D, X)[0]; run("service", "select remind_finish(%s,true)", (rd[0],))
check("…and gets a reminder notification for that bridge", adm("select bridge_id::text from notifications where user_id=%s and kind='reminder'", (X,)) == [(D,)])
check("recipient can't remind back through a pending send", run(X, "select remindable('bridge',%s)", (D,)) == [])
conn.execute("update bridges set direct_status='declined' where id=%s", (D,))
check("declined send -> not remindable", run(A, "select remindable('bridge',%s)", (D,)) == [])
conn.execute("delete from pod_reminders where id=%s", (rd[0],)); conn.execute("delete from notifications where user_id=%s", (X,))
run(C, "update profiles set email_reminders=true where id=auth.uid()"); run(C, "select block_user(%s)", (A,))
try: prep(A, "bridge", b4id, C, True); check("blocked -> unexpectedly ok", False)
except psycopg.Error as e: check("blocks respected (target blocked sender)", "not in this pod" in str(e))
print("group pods")
P = str(run(A, "select create_group_pod(%s, %s::uuid[])", (f"Rem {tag}", [B, X, G]))[0][0])
try: prep(A, "group", P, B, True); check("no clip -> unexpectedly ok", False)
except psycopg.Error as e: check("nothing shared yet -> no reminder", "Nothing shared" in str(e))
K = str(run(A, "select share_to_group_pod(%s,'Group ep','https://example.org/gep','Podcast','')", (P,))[0][0])
check("group remindable: everyone who hasn't answered, guests too", sorted(str(x[0]) for x in run(A, "select remindable('group',%s)", (P,))) == sorted([B, X, G]))
rg = prep(A, "group", P, X)[0]; run("service", "select remind_finish(%s,true)", (rg[0],))
check("group reminder notifies with the pod + latest clip", adm("select group_pod_id::text, title from notifications where user_id=%s and kind='reminder'", (X,)) == [(P, "Group ep")])
run(B, "select answer_group_clip_v2(%s,'ok',7)", (K,))
check("answered members drop out of remindable (only the guest left)", [str(x[0]) for x in run(A, "select remindable('group',%s)", (P,))] == [G])
K2 = str(run(A, "select share_to_group_pod(%s,'Newer ep','https://example.org/gep2','Podcast','')", (P,))[0][0])
check("new clip -> B remindable again (latest clip unanswered); X still within 24h", sorted(str(x[0]) for x in run(A, "select remindable('group',%s)", (P,))) == sorted([B, G]))
check("members can remind too, not just the owner (B can remind A)", sorted(str(x[0]) for x in run(B, "select remindable('group',%s)", (P,))) == sorted([A, G]))
print("daily cap")
pods = []
for i in range(11):
    bb = run(E, "select id, invite_token from create_bridge(%s,%s,'https://example.org/cap')", (f"Eve{tag}", f"Cap {i}"))[0]; run(X, "select join_bridge(%s,%s)", (bb[1], f"Xan{tag}")); pods.append(str(bb[0]))
for p in pods[:10]: run("service", "select remind_finish(%s,true)", (prep(E, "bridge", p, X)[0][0],))
try: prep(E, "bridge", pods[10], X); check("cap -> unexpectedly ok", False)
except psycopg.Error as e: check("~10 reminders per sender per day", "10 reminders" in str(e))
for u in (A, B, C, G, E, X): conn.execute("delete from auth.users where id=%s", (u,))
print(f"\n{passed} passed, {failed} failed")
raise SystemExit(1 if failed else 0)
